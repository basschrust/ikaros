SELECT "INDEX_SYMBOL", "DATE", "OPEN", "HIGH", "LOW", "CLOSE", "SOURCE"
FROM DAEDALUS.MARKET_DATA.INDEX_PRICES
WHERE "INDEX_SYMBOL" = 'WIG20'
ORDER BY "DATE" DESC;

-- Check missing days against registered GPW equity observations (not a holiday calendar).
SELECT MAX("DATE") AS LAST_WIG20_SESSION, COUNT(*) AS OBSERVATIONS
FROM DAEDALUS.MARKET_DATA.INDEX_PRICES
WHERE "INDEX_SYMBOL" = 'WIG20';
