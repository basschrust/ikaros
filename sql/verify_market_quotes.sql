USE DATABASE DAEDALUS;
USE SCHEMA MARKET_DATA;

-- Provider mappings, without guessed derivative aliases.
SELECT m."INDEX_SYMBOL", p."PROVIDER_CODE", m."PROVIDER_SYMBOL", m."IS_ACTIVE"
FROM "INDEX_PROVIDER_SYMBOLS" m JOIN "PROVIDERS" p ON p."PROVIDER_ID"=m."PROVIDER_ID"
ORDER BY 1,2;
SELECT p."PROVIDER_CODE", COUNT(*) AS CONTRACT_MAPPINGS
FROM "DERIVATIVE_PROVIDER_SYMBOLS" m JOIN "PROVIDERS" p ON p."PROVIDER_ID"=m."PROVIDER_ID"
GROUP BY 1 ORDER BY 1;

-- Integer primary keys and price-level statuses (never SHA strings as IDs).
SELECT p."PROVIDER_CODE", c."VALIDATION_STATUS", c."VALIDATION_REASON", COUNT(*) AS OBSERVATIONS
FROM "INDEX_PRICE_CANDIDATES" c JOIN "PROVIDERS" p ON p."PROVIDER_ID"=c."PROVIDER_ID"
GROUP BY 1,2,3 ORDER BY 1,2,3;
SELECT p."PROVIDER_CODE", c."VALIDATION_STATUS", c."VALIDATION_REASON", COUNT(*) AS OBSERVATIONS
FROM "DERIVATIVE_PRICE_CANDIDATES" c JOIN "PROVIDERS" p ON p."PROVIDER_ID"=c."PROVIDER_ID"
GROUP BY 1,2,3 ORDER BY 1,2,3;

-- Selected index candidates (and existing rows with NULL provenance).
SELECT i."INDEX_SYMBOL", TO_DATE(i."DATE") AS DAY, i."CLOSE", i."CANDIDATE_ID",
       i."SELECTION_REASON", p."PROVIDER_CODE", c."CONTENT_HASH"
FROM "INDEX_PRICES" i LEFT JOIN "INDEX_PRICE_CANDIDATES" c ON c."CANDIDATE_ID"=i."CANDIDATE_ID"
LEFT JOIN "PROVIDERS" p ON p."PROVIDER_ID"=i."PROVIDER_ID"
WHERE i."INDEX_SYMBOL"='WIG20' ORDER BY DAY DESC LIMIT 20;

-- Selected futures/options candidates.
SELECT d."CONTRACT_ID", TO_DATE(d."DATE") AS DAY, d."CLOSE", d."VOLUME",
       d."CANDIDATE_ID", d."SELECTION_REASON", p."PROVIDER_CODE"
FROM "DERIVATIVE_PRICES" d LEFT JOIN "DERIVATIVE_PRICE_CANDIDATES" c ON c."CANDIDATE_ID"=d."CANDIDATE_ID"
LEFT JOIN "PROVIDERS" p ON p."PROVIDER_ID"=d."PROVIDER_ID"
ORDER BY DAY DESC, d."CONTRACT_ID" LIMIT 50;

-- Duplicate authoritative instrument/day records: each count should be zero.
SELECT 'INDEX' AS DATASET, COUNT(*) AS DUPLICATE_KEYS FROM (
    SELECT "INDEX_SYMBOL", TO_DATE("DATE") FROM "INDEX_PRICES"
    GROUP BY 1,2 HAVING COUNT(*)>1)
UNION ALL
SELECT 'DERIVATIVE', COUNT(*) FROM (
    SELECT "CONTRACT_ID", TO_DATE("DATE") FROM "DERIVATIVE_PRICES"
    GROUP BY 1,2 HAVING COUNT(*)>1);

-- Orphaned non-null candidate references: should be zero.
SELECT 'INDEX' AS DATASET, COUNT(*) AS ORPHANED
FROM "INDEX_PRICES" p WHERE p."CANDIDATE_ID" IS NOT NULL AND NOT EXISTS (
    SELECT 1 FROM "INDEX_PRICE_CANDIDATES" c WHERE c."CANDIDATE_ID"=p."CANDIDATE_ID")
UNION ALL
SELECT 'DERIVATIVE', COUNT(*) FROM "DERIVATIVE_PRICES" p
WHERE p."CANDIDATE_ID" IS NOT NULL AND NOT EXISTS (
    SELECT 1 FROM "DERIVATIVE_PRICE_CANDIDATES" c WHERE c."CANDIDATE_ID"=p."CANDIDATE_ID");
