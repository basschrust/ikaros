-- Ikaros layer 2: derived daily stock features, separate from the raw PRICES table.
-- Run in Snowsight while using a role with CREATE TABLE/VIEW privileges.
CREATE TABLE IF NOT EXISTS DAEDALUS.MARKET_DATA.GPW_STOCK_METRICS_DAILY (
    SYMBOL VARCHAR NOT NULL,
    TRADE_DATE DATE NOT NULL,
    CLOSE_PRICE FLOAT,
    DAILY_LOG_RETURN FLOAT,
    DAILY_SIMPLE_RETURN FLOAT,
    VOLUME_AVG_20D FLOAT,
    VOLUME_AVG_60D FLOAT,
    VOLUME_AVG_252D FLOAT,
    CLOSE_SMA_20D FLOAT,
    CLOSE_SMA_60D FLOAT,
    VOLUME_RELATIVE_20D FLOAT,
    VOLATILITY_DAILY_20D FLOAT,
    VOLATILITY_ANNUAL_20D FLOAT,
    VOLATILITY_ANNUAL_252D FLOAT,
    MEAN_ABS_LOG_RETURN_252D FLOAT,
    HIGH_52W FLOAT,
    LOW_52W FLOAT,
    POSITION_52W FLOAT,
    OBSERVATIONS_52W NUMBER(10,0),
    COMPLETE_52W BOOLEAN,
    CALC_VERSION NUMBER(5,0) DEFAULT 1,
    CALCULATED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);

CREATE OR REPLACE VIEW DAEDALUS.MARKET_DATA.GPW_STOCK_METRICS_LATEST AS
SELECT m.*,
       DATEDIFF('day', m.TRADE_DATE, CURRENT_DATE()) AS CALENDAR_DAYS_OLD
FROM DAEDALUS.MARKET_DATA.GPW_STOCK_METRICS_DAILY m
QUALIFY ROW_NUMBER() OVER (
    PARTITION BY m.SYMBOL ORDER BY m.TRADE_DATE DESC
) = 1;
