-- Ikaros L2 derived analytics: persisted values have explicit decimal scales.
-- This CREATE does NOT migrate an existing FLOAT-backed Snowflake table.
-- Audit/migrate populated Snowflake tables separately, with a clone backup.
CREATE TABLE IF NOT EXISTS DAEDALUS.MARKET_DATA.GPW_STOCK_METRICS_DAILY (
    SYMBOL VARCHAR NOT NULL,
    TRADE_DATE DATE NOT NULL,
    CLOSE_PRICE NUMBER(24,8),
    DAILY_LOG_RETURN NUMBER(24,12),
    DAILY_SIMPLE_RETURN NUMBER(24,12),
    VOLUME_AVG_20D NUMBER(24,6),
    VOLUME_AVG_60D NUMBER(24,6),
    VOLUME_AVG_252D NUMBER(24,6),
    CLOSE_SMA_20D NUMBER(24,8),
    CLOSE_SMA_60D NUMBER(24,8),
    VOLUME_RELATIVE_20D NUMBER(24,12),
    VOLATILITY_DAILY_20D NUMBER(24,12),
    VOLATILITY_ANNUAL_20D NUMBER(24,12),
    VOLATILITY_ANNUAL_252D NUMBER(24,12),
    MEAN_ABS_LOG_RETURN_252D NUMBER(24,12),
    HIGH_52W NUMBER(24,8),
    LOW_52W NUMBER(24,8),
    POSITION_52W NUMBER(24,12),
    OBSERVATIONS_52W NUMBER(10,0),
    COMPLETE_52W BOOLEAN,
    CALC_VERSION NUMBER(5,0) DEFAULT 1,
    CALCULATED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);

CREATE OR REPLACE VIEW DAEDALUS.MARKET_DATA.GPW_STOCK_METRICS_LATEST AS
SELECT m.*,
       DATEDIFF('day', m.TRADE_DATE, CURRENT_DATE()) AS CALENDAR_DAYS_OLD
FROM DAEDALUS.MARKET_DATA.GPW_STOCK_METRICS_DAILY m
QUALIFY ROW_NUMBER() OVER (
    PARTITION BY m.SYMBOL ORDER BY m.TRADE_DATE DESC
) = 1;
