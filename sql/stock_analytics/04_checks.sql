SELECT SYMBOL, TRADE_DATE, CLOSE_PRICE, VOLUME_AVG_20D,
       VOLATILITY_ANNUAL_20D, VOLATILITY_ANNUAL_252D,
       HIGH_52W, LOW_52W, OBSERVATIONS_52W, COMPLETE_52W
FROM DAEDALUS.MARKET_DATA.GPW_STOCK_METRICS_LATEST
ORDER BY SYMBOL LIMIT 50;

-- Source quality diagnostic: duplicate raw prices must be resolved eventually.
SELECT "SYMBOL", TO_DATE("DATE") AS TRADE_DATE, COUNT(*) AS N
FROM DAEDALUS.MARKET_DATA.PRICES
GROUP BY 1, 2
HAVING COUNT(*) > 1
ORDER BY N DESC, 1, 2
LIMIT 30;

-- Raw date vs derived date: after a catch-up job they should converge.
WITH RAW AS (
    SELECT "SYMBOL" AS SYMBOL, MAX(TO_DATE("DATE")) AS RAW_LATEST
    FROM DAEDALUS.MARKET_DATA.PRICES GROUP BY 1
)
SELECT r.SYMBOL, r.RAW_LATEST, m.TRADE_DATE AS METRICS_LATEST
FROM RAW r
LEFT JOIN DAEDALUS.MARKET_DATA.GPW_STOCK_METRICS_LATEST m
  ON r.SYMBOL = m.SYMBOL
WHERE r.RAW_LATEST > COALESCE(m.TRADE_DATE, '1900-01-01'::DATE)
ORDER BY r.SYMBOL;
