-- IKAROS: WIG20 INDEX + GPW DERIVATIVE CANDIDATE SCHEMA

-- Additive: existing prices and contracts are never deleted or overwritten.

-- Stop the legacy index/derivative writers before switching to this pipeline.

-- Requires existing PROVIDERS and registered DERIVATIVE_CONTRACTS.

USE DATABASE DAEDALUS;

USE SCHEMA MARKET_DATA;


-- A. New sequences and tables (repeatable DDL).

CREATE TABLE IF NOT EXISTS "INDEX_PRICES" (
        "INDEX_SYMBOL" VARCHAR(128) NOT NULL, "DATE" DATE NOT NULL,
        "OPEN" NUMBER(24,8), "HIGH" NUMBER(24,8), "LOW" NUMBER(24,8), "CLOSE" NUMBER(24,8),
        "SOURCE" VARCHAR(128), "CANDIDATE_ID" NUMBER(38,0),
        "PROVIDER_ID" NUMBER(38,0), "SELECTION_REASON" VARCHAR(128),
        "SELECTED_AT" TIMESTAMP_NTZ);

CREATE TABLE IF NOT EXISTS "DERIVATIVE_PRICES" (
        "CONTRACT_ID" VARCHAR(128) NOT NULL, "DATE" DATE NOT NULL,
        "OPEN" NUMBER(24,8), "HIGH" NUMBER(24,8), "LOW" NUMBER(24,8), "CLOSE" NUMBER(24,8),
        "VOLUME" NUMBER(38,0), "OPEN_INTEREST" NUMBER(38,0), "SETTLEMENT" NUMBER(24,8),
        "SOURCE" VARCHAR(128), "INGESTED_AT" TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP,
        "CANDIDATE_ID" NUMBER(38,0), "PROVIDER_ID" NUMBER(38,0),
        "SELECTION_REASON" VARCHAR(128), "SELECTED_AT" TIMESTAMP_NTZ);

CREATE SEQUENCE IF NOT EXISTS "INDEX_PROVIDER_SYMBOLS_ID_SEQ" START WITH 1 INCREMENT BY 1;

CREATE SEQUENCE IF NOT EXISTS "INDEX_PRICE_CANDIDATES_ID_SEQ" START WITH 1 INCREMENT BY 1;

CREATE TABLE IF NOT EXISTS "INDEX_PROVIDER_SYMBOLS" (
            "PROVIDER_SYMBOL_ID" NUMBER(38,0) PRIMARY KEY,
            "INDEX_SYMBOL" VARCHAR(128) NOT NULL,
            "PROVIDER_ID" NUMBER(38,0) NOT NULL,
            "PROVIDER_SYMBOL" VARCHAR(128) NOT NULL,
            "VALID_FROM" DATE NOT NULL,
            "VALID_TO" DATE,
            "IS_ACTIVE" BOOLEAN NOT NULL DEFAULT TRUE,
            "CREATED_AT" TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP,
            FOREIGN KEY ("PROVIDER_ID") REFERENCES "PROVIDERS"("PROVIDER_ID")
        );

CREATE TABLE IF NOT EXISTS "INDEX_PRICE_CANDIDATES" (
            "CANDIDATE_ID" NUMBER(38,0) PRIMARY KEY,
            "CONTENT_HASH" VARCHAR(64) NOT NULL UNIQUE,
            "INDEX_SYMBOL" VARCHAR(128) NOT NULL,
            "PROVIDER_ID" NUMBER(38,0) NOT NULL,
            "PROVIDER_SYMBOL_ID" NUMBER(38,0) NOT NULL,
            "DATE" DATE NOT NULL,
            "OPEN" NUMBER(24,8), "HIGH" NUMBER(24,8), "LOW" NUMBER(24,8),
            "CLOSE" NUMBER(24,8), "VOLUME" NUMBER(38,0),
            "SETTLEMENT" NUMBER(24,8), "OPEN_INTEREST" NUMBER(38,0),
            "VALIDATION_STATUS" VARCHAR(16) NOT NULL,
            "VALIDATION_REASON" VARCHAR(128),
            "INGESTED_AT" TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP,
            FOREIGN KEY ("PROVIDER_ID") REFERENCES "PROVIDERS"("PROVIDER_ID"),
            FOREIGN KEY ("PROVIDER_SYMBOL_ID") REFERENCES "INDEX_PROVIDER_SYMBOLS"("PROVIDER_SYMBOL_ID")
        );

CREATE SEQUENCE IF NOT EXISTS "DERIVATIVE_PROVIDER_SYMBOLS_ID_SEQ" START WITH 1 INCREMENT BY 1;

CREATE SEQUENCE IF NOT EXISTS "DERIVATIVE_PRICE_CANDIDATES_ID_SEQ" START WITH 1 INCREMENT BY 1;

CREATE TABLE IF NOT EXISTS "DERIVATIVE_PROVIDER_SYMBOLS" (
            "PROVIDER_SYMBOL_ID" NUMBER(38,0) PRIMARY KEY,
            "CONTRACT_ID" VARCHAR(128) NOT NULL,
            "PROVIDER_ID" NUMBER(38,0) NOT NULL,
            "PROVIDER_SYMBOL" VARCHAR(128) NOT NULL,
            "VALID_FROM" DATE NOT NULL,
            "VALID_TO" DATE,
            "IS_ACTIVE" BOOLEAN NOT NULL DEFAULT TRUE,
            "CREATED_AT" TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP,
            FOREIGN KEY ("PROVIDER_ID") REFERENCES "PROVIDERS"("PROVIDER_ID")
        );

CREATE TABLE IF NOT EXISTS "DERIVATIVE_PRICE_CANDIDATES" (
            "CANDIDATE_ID" NUMBER(38,0) PRIMARY KEY,
            "CONTENT_HASH" VARCHAR(64) NOT NULL UNIQUE,
            "CONTRACT_ID" VARCHAR(128) NOT NULL,
            "PROVIDER_ID" NUMBER(38,0) NOT NULL,
            "PROVIDER_SYMBOL_ID" NUMBER(38,0) NOT NULL,
            "DATE" DATE NOT NULL,
            "OPEN" NUMBER(24,8), "HIGH" NUMBER(24,8), "LOW" NUMBER(24,8),
            "CLOSE" NUMBER(24,8), "VOLUME" NUMBER(38,0),
            "SETTLEMENT" NUMBER(24,8), "OPEN_INTEREST" NUMBER(38,0),
            "VALIDATION_STATUS" VARCHAR(16) NOT NULL,
            "VALIDATION_REASON" VARCHAR(128),
            "INGESTED_AT" TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP,
            FOREIGN KEY ("PROVIDER_ID") REFERENCES "PROVIDERS"("PROVIDER_ID"),
            FOREIGN KEY ("PROVIDER_SYMBOL_ID") REFERENCES "DERIVATIVE_PROVIDER_SYMBOLS"("PROVIDER_SYMBOL_ID")
        );


-- B. Extend existing authoritative tables only where columns are absent.

EXECUTE IMMEDIATE $$
DECLARE
    existing_columns NUMBER;
BEGIN
    SELECT COUNT(*) INTO :existing_columns
    FROM INFORMATION_SCHEMA.COLUMNS
    WHERE TABLE_CATALOG = CURRENT_DATABASE()
      AND TABLE_SCHEMA = CURRENT_SCHEMA()
      AND TABLE_NAME = 'INDEX_PRICES'
      AND COLUMN_NAME = 'CANDIDATE_ID';
    IF (existing_columns = 0) THEN
        EXECUTE IMMEDIATE 'ALTER TABLE "INDEX_PRICES" ADD COLUMN "CANDIDATE_ID" NUMBER(38,0)';
    END IF;
END;
$$;

