-- C. Check tables before seeding; all four candidate/mapping table counts start at zero.

SELECT TABLE_NAME, COUNT(*) AS COLUMN_COUNT
FROM INFORMATION_SCHEMA.COLUMNS
WHERE TABLE_SCHEMA = CURRENT_SCHEMA()
  AND TABLE_NAME IN (
    'INDEX_PROVIDER_SYMBOLS', 'DERIVATIVE_PROVIDER_SYMBOLS',
    'INDEX_PRICE_CANDIDATES', 'DERIVATIVE_PRICE_CANDIDATES',
    'INDEX_PRICES', 'DERIVATIVE_PRICES')
GROUP BY TABLE_NAME ORDER BY TABLE_NAME;

SELECT TABLE_NAME, COLUMN_NAME, DATA_TYPE
FROM INFORMATION_SCHEMA.COLUMNS
WHERE TABLE_SCHEMA=CURRENT_SCHEMA() AND
    TABLE_NAME IN ('INDEX_PRICE_CANDIDATES','DERIVATIVE_PRICE_CANDIDATES')
    AND COLUMN_NAME='CANDIDATE_ID';

