-- Read-only inspection of ALL permanent tables in the current Snowflake schema.
-- USE DATABASE DAEDALUS; USE SCHEMA MARKET_DATA; before executing.
-- FLOAT/DOUBLE/REAL aliases appear as FLOAT in INFORMATION_SCHEMA.COLUMNS.
SELECT
  TABLE_CATALOG, TABLE_SCHEMA, TABLE_NAME, COLUMN_NAME,
  DATA_TYPE, NUMERIC_PRECISION, NUMERIC_SCALE
FROM INFORMATION_SCHEMA.COLUMNS
WHERE TABLE_SCHEMA = CURRENT_SCHEMA()
  AND DATA_TYPE IN ('FLOAT', 'DOUBLE', 'DOUBLE PRECISION', 'REAL', 'FLOAT4', 'FLOAT8')
ORDER BY TABLE_NAME, ORDINAL_POSITION;

-- Show all fixed-point columns as well for policy comparison:
SELECT
  TABLE_NAME, COLUMN_NAME, DATA_TYPE, NUMERIC_PRECISION, NUMERIC_SCALE
FROM INFORMATION_SCHEMA.COLUMNS
WHERE TABLE_SCHEMA = CURRENT_SCHEMA()
  AND DATA_TYPE IN ('NUMBER', 'DECIMAL', 'NUMERIC')
ORDER BY TABLE_NAME, ORDINAL_POSITION;
