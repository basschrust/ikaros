-- Additive migration for DAEDALUS.MARKET_DATA.
-- Existing DERIVATIVE_CONTRACTS, DERIVATIVE_PRICES and DERIVATIVE_CANDIDATES
-- remain unchanged. Apply in the target database/schema after review.
-- No automatic promotion or creation of synthetic prices.

CREATE TABLE IF NOT EXISTS "DERIVATIVE_SPECIFICATIONS" (
    "CONTRACT_ID" VARCHAR NOT NULL,
    "PRODUCT_FAMILY" VARCHAR NOT NULL,  -- INDEX_FUTURE, EQUITY_FUTURE, FX_FUTURE, INDEX_OPTION
    "UNDERLYING_TYPE" VARCHAR NOT NULL, -- INDEX, EQUITY, FX_PAIR, OTHER
    "EXERCISE_STYLE" VARCHAR,            -- EUROPEAN / AMERICAN; NULL for futures
    "SETTLEMENT_TYPE" VARCHAR,           -- CASH / PHYSICAL; verified externally
    "PRICE_UNIT" VARCHAR,                -- INDEX_POINTS, PLN_PER_SHARE, etc.
    "TICK_SIZE" NUMBER(20,8),
    "LOT_SIZE" NUMBER(20,8),
    "SPECIFICATION_SOURCE" VARCHAR NOT NULL,
    "SOURCE_URL" VARCHAR,
    "VERIFIED_AT" TIMESTAMP_NTZ,
    "CREATED_AT" TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP(),
    "UPDATED_AT" TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);

-- One logical row per CONTRACT_ID must be enforced by application MERGE logic:
-- standard Snowflake table UNIQUE constraints may not be enforced.
-- For verified specifications, join back to DERIVATIVE_CONTRACTS.
CREATE OR REPLACE VIEW "DERIVATIVE_UNIVERSE" AS
SELECT c."CONTRACT_ID", c."SYMBOL", c."INSTRUMENT_TYPE", c."UNDERLYING_SYMBOL",
       c."EXPIRY_DATE", c."CURRENCY", c."MULTIPLIER", c."STRIKE",
       c."OPTION_SIDE", c."SOURCE", s."PRODUCT_FAMILY", s."UNDERLYING_TYPE",
       s."EXERCISE_STYLE", s."SETTLEMENT_TYPE", s."PRICE_UNIT", s."TICK_SIZE",
       s."LOT_SIZE", s."SPECIFICATION_SOURCE", s."SOURCE_URL", s."VERIFIED_AT"
FROM "DERIVATIVE_CONTRACTS" c
LEFT JOIN "DERIVATIVE_SPECIFICATIONS" s ON s."CONTRACT_ID" = c."CONTRACT_ID";
