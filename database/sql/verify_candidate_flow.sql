-- Read-only Snowflake verification following setup and test ingestion.
USE DATABASE DAEDALUS;
USE SCHEMA MARKET_DATA;

-- Candidate volumes, latest date and rejected evidence.
SELECT 'EQUITY' AS DOMAIN, COUNT(*) AS ROWS,
       COUNT_IF("VALIDATION_STATUS"='VALID') AS VALID_ROWS,
       COUNT_IF("VALIDATION_STATUS"='REJECTED') AS REJECTED_ROWS,
       MAX("DATE") AS LAST_DATE FROM "PRICES_CANDIDATES"
UNION ALL
SELECT 'INDEX',COUNT(*),COUNT_IF("VALIDATION_STATUS"='VALID'),
       COUNT_IF("VALIDATION_STATUS"='REJECTED'),MAX("DATE") FROM "INDEX_PRICE_CANDIDATES"
UNION ALL
SELECT 'DERIVATIVE',COUNT(*),COUNT_IF("VALIDATION_STATUS"='VALID'),
       COUNT_IF("VALIDATION_STATUS"='REJECTED'),MAX("DATE") FROM "DERIVATIVE_PRICE_CANDIDATES"
UNION ALL
SELECT 'FX',COUNT(*),COUNT_IF("VALIDATION_STATUS"='VALID'),
       COUNT_IF("VALIDATION_STATUS"='REJECTED'),MAX("DATE") FROM "FX_RATE_CANDIDATES"
UNION ALL
SELECT 'RATE',COUNT(*),COUNT_IF("VALIDATION_STATUS"='VALID'),
       COUNT_IF("VALIDATION_STATUS"='REJECTED'),MAX("DATE") FROM "RATE_OBSERVATION_CANDIDATES";

-- All five counts MUST be zero. Existing legacy rows with NULL candidate IDs
-- are allowed until revisited/backfilled; this checks only populated links.
SELECT 'EQUITY' DOMAIN, COUNT(*) AS ORPHANED
  FROM "PRICES" p WHERE p."CANDIDATE_ID" IS NOT NULL
  AND NOT EXISTS (SELECT 1 FROM "PRICES_CANDIDATES" c
                  WHERE c."CANDIDATE_ID"=p."CANDIDATE_ID")
UNION ALL
SELECT 'INDEX',COUNT(*) FROM "INDEX_PRICES" p
  WHERE p."CANDIDATE_ID" IS NOT NULL
  AND NOT EXISTS (SELECT 1 FROM "INDEX_PRICE_CANDIDATES" c
                  WHERE c."CANDIDATE_ID"=p."CANDIDATE_ID")
UNION ALL
SELECT 'DERIVATIVE',COUNT(*) FROM "DERIVATIVE_PRICES" p
  WHERE p."CANDIDATE_ID" IS NOT NULL
  AND NOT EXISTS (SELECT 1 FROM "DERIVATIVE_PRICE_CANDIDATES" c
                  WHERE c."CANDIDATE_ID"=p."CANDIDATE_ID")
UNION ALL
SELECT 'FX',COUNT(*) FROM "FX_RATES" p
  WHERE p."CANDIDATE_ID" IS NOT NULL
  AND NOT EXISTS (SELECT 1 FROM "FX_RATE_CANDIDATES" c
                  WHERE c."CANDIDATE_ID"=p."CANDIDATE_ID")
UNION ALL
SELECT 'RATE',COUNT(*) FROM "RATE_OBSERVATIONS" p
  WHERE p."CANDIDATE_ID" IS NOT NULL
  AND NOT EXISTS (SELECT 1 FROM "RATE_OBSERVATION_CANDIDATES" c
                  WHERE c."CANDIDATE_ID"=p."CANDIDATE_ID");

-- Duplicate natural keys: stop promotion and reconcile if any are returned.
SELECT "CURRENCY_PAIR_ID", CAST("DATE" AS DATE), COUNT(*) AS ROWS
 FROM "FX_RATES" GROUP BY "CURRENCY_PAIR_ID",CAST("DATE" AS DATE) HAVING COUNT(*)>1;
SELECT "SERIES_ID", CAST("DATE" AS DATE), COUNT(*) AS ROWS
 FROM "RATE_OBSERVATIONS" GROUP BY "SERIES_ID",CAST("DATE" AS DATE) HAVING COUNT(*)>1;

-- Source-level diagnostic (reference NBP mids are not executable market OHLCV).
SELECT "SOURCE_CODE","QUOTE_KIND","VALIDATION_STATUS",COUNT(*) AS ROWS
FROM "FX_RATE_CANDIDATES"
GROUP BY "SOURCE_CODE","QUOTE_KIND","VALIDATION_STATUS"
ORDER BY "SOURCE_CODE","QUOTE_KIND","VALIDATION_STATUS";
